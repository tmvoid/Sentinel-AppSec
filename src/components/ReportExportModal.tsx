import React, { useState } from 'react';
import {
  Check,
  Copy,
  Download,
  FileCode,
  FileDown,
  Loader2,
  Shield,
  X,
} from 'lucide-react';
import type { AuditReport } from '../types/audit.ts';
import { exportAuditReportToPdf } from '../utils/pdfExport.ts';
import { SENTINEL_LOGO_SRC } from '../utils/assets.ts';

interface ReportExportModalProps {
  report: AuditReport | null;
  isOpen: boolean;
  onClose: () => void;
}

export function generateMarkdownReport(report: AuditReport): string {
  const lines: string[] = [
    `# Sentinel AppSec — Application Security Verification Report`,
    ``,
    `- **Project Name**: ${report.projectName}`,
    `- **Report ID**: \`${report.id}\``,
    `- **Timestamp**: ${new Date(report.timestamp).toUTCString()}`,
    `- **Audit Duration**: ${report.durationMs} ms`,
    report.targetSummary.targetUrl
      ? `- **Target URL**: ${report.targetSummary.targetUrl}`
      : '',
    report.targetSummary.githubRepoUrl
      ? `- **GitHub Repository**: ${report.targetSummary.githubRepoUrl}`
      : '',
    `- **Source Files Analyzed**: ${report.targetSummary.filesCount}`,
    `- **Verified Vulnerabilities Found**: ${report.findings.length}`,
    `- **Passed Security Controls**: ${report.passedChecks.length}`,
    ``,
    `---`,
    ``,
    `## 1. Executive Summary`,
    ``,
    report.findings.length === 0
      ? `All enabled deterministic security checks passed with **0 verified vulnerabilities**. No synthetic or speculative warnings are generated.`
      : `The Sentinel AppSec engine identified **${report.findings.length} verified security finding(s)** backed by empirical HTTP header responses, route signatures, OSV.dev CVE advisories, or exact source code line matches.`,
    ``,
    `## 2. Verified Findings (${report.findings.length})`,
    ``,
  ].filter((l) => l !== '');

  if (report.findings.length === 0) {
    lines.push(
      `_Zero verified vulnerabilities detected across enabled modules._`,
      ``
    );
  } else {
    report.findings.forEach((f, idx) => {
      lines.push(
        `### ${idx + 1}. [${f.severity.toUpperCase()}] ${f.title}`,
        `- **Module**: \`${f.module}\` · **CWE**: \`${f.cwe}\` · **OWASP**: \`${f.owasp}\``,
        `- **Affected Target**: \`${f.affectedTarget}\``,
        `- **Summary**: ${f.summary}`,
        `- **Impact**: ${f.impact}`,
        ``,
        `**Empirical Proof**:`,
        '```text',
        f.evidence.rawProof,
        '```',
        ``,
        `**Reproduction Command**:`,
        '```bash',
        f.evidence.reproductionCommand,
        '```',
        ``,
        `**Recommended Fix**: ${f.remediation.summary}`,
        ...(f.remediation.snippets[0]
          ? [
              '```' + f.remediation.snippets[0].language,
              f.remediation.snippets[0].code,
              '```',
            ]
          : []),
        ``
      );
    });
  }

  lines.push(
    `## 3. Verified Passed Security Controls (${report.passedChecks.length})`,
    ``
  );
  report.passedChecks.forEach((p) => {
    lines.push(`- **[PASS] ${p.title}** (\`${p.target}\`) — ${p.proofSummary}`);
  });

  lines.push(
    ``,
    `---`,
    `_Generated by Sentinel AppSec — Engineered by [Tanmay Bhardwaj](https://www.linkedin.com/in/tanmaysbhardwaj/) ([@tmvoid](https://github.com/tmvoid)). Zero-hallucination empirical verification._`
  );

  return lines.join('\n');
}

export const ReportExportModal: React.FC<ReportExportModalProps> = ({
  report,
  isOpen,
  onClose,
}) => {
  const [copiedMd, setCopiedMd] = useState(false);
  const [isGeneratingPdf, setIsGeneratingPdf] = useState(false);
  const [pdfSaved, setPdfSaved] = useState(false);
  const [logoError, setLogoError] = useState(false);

  if (!isOpen || !report) return null;

  const markdownText = generateMarkdownReport(report);

  const handleCopyMarkdown = async () => {
    try {
      await navigator.clipboard.writeText(markdownText);
      setCopiedMd(true);
      setTimeout(() => setCopiedMd(false), 2000);
    } catch {
      // ignore
    }
  };

  const handleDownloadFile = (
    content: string,
    ext: 'md' | 'json',
    mime: string
  ) => {
    const blob = new Blob([content], { type: mime });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    const slug = report.projectName
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/^-|-$/g, '');
    a.href = url;
    a.download = `sentinel-audit-${slug || 'report'}.${ext}`;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
  };

  const handleSavePdf = async () => {
    setIsGeneratingPdf(true);
    try {
      await exportAuditReportToPdf(report);
      setPdfSaved(true);
      setTimeout(() => setPdfSaved(false), 2500);
    } finally {
      setIsGeneratingPdf(false);
    }
  };

  const criticalCount = report.findings.filter(
    (f) => f.severity === 'critical'
  ).length;
  const highCount = report.findings.filter((f) => f.severity === 'high').length;
  const mediumCount = report.findings.filter(
    (f) => f.severity === 'medium'
  ).length;
  const lowCount = report.findings.filter((f) => f.severity === 'low').length;

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center bg-black/75 p-4 backdrop-blur-sm">
      <div className="glass-workspace relative flex max-h-[90vh] w-full max-w-4xl flex-col overflow-hidden rounded-2xl text-[#F8FAFC]">
        {/* Top Action Bar */}
        <div className="flex flex-wrap items-center justify-between gap-4 border-b border-white/[0.09] bg-white/[0.03] px-6 py-4">
          <div className="text-sm font-semibold text-white">
            Sentinel AppSec — Application Security Verification Report
          </div>
          <div className="flex flex-wrap items-center gap-2">
            <button
              onClick={handleCopyMarkdown}
              className="glass-subpanel flex items-center gap-1.5 rounded-md px-3 py-1.5 text-xs font-medium text-[#E2E8F0] hover:border-white/[0.22] hover:text-white transition-colors whitespace-nowrap shrink-0"
            >
              {copiedMd ? (
                <>
                  <Check className="h-3.5 w-3.5 text-[#10B981]" />
                  <span>Copied Markdown</span>
                </>
              ) : (
                <>
                  <Copy className="h-3.5 w-3.5" />
                  <span>Copy Markdown</span>
                </>
              )}
            </button>
            <button
              onClick={() =>
                handleDownloadFile(markdownText, 'md', 'text/markdown')
              }
              className="glass-subpanel flex items-center gap-1.5 rounded-md px-3 py-1.5 text-xs font-medium text-[#E2E8F0] hover:border-white/[0.22] hover:text-white transition-colors whitespace-nowrap shrink-0"
            >
              <Download className="h-3.5 w-3.5" />
              <span>Download .MD</span>
            </button>
            <button
              onClick={() =>
                handleDownloadFile(
                  JSON.stringify(report, null, 2),
                  'json',
                  'application/json'
                )
              }
              className="glass-subpanel flex items-center gap-1.5 rounded-md px-3 py-1.5 text-xs font-medium text-[#E2E8F0] hover:border-white/[0.22] hover:text-white transition-colors whitespace-nowrap shrink-0"
            >
              <FileCode className="h-3.5 w-3.5" />
              <span>Download .JSON</span>
            </button>
            <button
              onClick={handleSavePdf}
              disabled={isGeneratingPdf}
              className="flex items-center gap-1.5 rounded-md bg-[#0078D4] px-3.5 py-1.5 text-xs font-semibold text-white hover:bg-[#1084E0] disabled:opacity-50 transition-colors whitespace-nowrap shrink-0 shadow-[0_4px_16px_rgba(0,120,212,0.4)]"
            >
              {isGeneratingPdf ? (
                <>
                  <Loader2 className="h-3.5 w-3.5 animate-spin" />
                  <span>Generating PDF...</span>
                </>
              ) : pdfSaved ? (
                <>
                  <Check className="h-3.5 w-3.5 text-white" />
                  <span>PDF Downloaded</span>
                </>
              ) : (
                <>
                  <FileDown className="h-3.5 w-3.5" />
                  <span>Save PDF</span>
                </>
              )}
            </button>
            <button
              onClick={onClose}
              className="glass-subpanel rounded-md p-1.5 text-[#94A3B8] hover:text-white transition-colors"
              aria-label="Close modal"
            >
              <X className="h-4 w-4" />
            </button>
          </div>
        </div>

        {/* Certificate / Report Preview Body with Centered Geometric Sentinel Logo Watermark */}
        <div className="relative flex-1 overflow-y-auto p-6 sm:p-8 space-y-6">
          <div
            aria-hidden="true"
            className="pointer-events-none select-none fixed inset-0 z-0 flex items-center justify-center"
          >
            <img
              src={SENTINEL_LOGO_SRC}
              alt=""
              className="h-80 w-80 object-contain opacity-[0.045] filter contrast-150"
            />
          </div>

          {/* Official Sentinel Header Banner */}
          <div className="relative z-10 flex flex-col sm:flex-row items-start sm:items-center justify-between gap-4 border-b border-white/[0.09] pb-6">
            <div className="flex items-center gap-4">
              <div className="relative flex h-14 w-14 items-center justify-center rounded-full overflow-hidden p-0.5 shrink-0 ring-2 ring-cyan-500/40 shadow-[0_0_18px_rgba(6,182,212,0.3)] bg-[#070B14]">
                <img
                  src={SENTINEL_LOGO_SRC}
                  alt="Sentinel AppSec Logo"
                  className="h-full w-full object-cover rounded-full"
                />
              </div>
              <div>
                <div className="text-[11px] font-mono tracking-wider text-[#38BDF8]">
                  SENTINEL APPSEC · APPLICATION SECURITY VERIFICATION
                </div>
                <h2 className="font-display text-xl font-bold text-white mt-0.5">
                  {report.projectName}
                </h2>
                <div className="flex flex-wrap items-center gap-2 text-xs text-[#94A3B8] font-mono mt-1">
                  <span>Report ID: {report.id}</span>
                  <span aria-hidden="true">·</span>
                  <span>{new Date(report.timestamp).toLocaleString()}</span>
                  <span aria-hidden="true">·</span>
                  <span className="tabular-nums">{report.durationMs} ms</span>
                </div>
              </div>
            </div>

            <div className="text-left sm:text-right font-mono">
              <div className="text-xs text-[#94A3B8]">Verification Posture</div>
              <div
                className={`text-sm font-semibold mt-0.5 ${
                  report.findings.length === 0
                    ? 'text-[#10B981]'
                    : criticalCount > 0 || highCount > 0
                    ? 'text-[#EF4444]'
                    : 'text-[#F59E0B]'
                }`}
              >
                {report.findings.length === 0
                  ? 'VERIFIED CLEAN (0 ISSUES)'
                  : `${report.findings.length} VERIFIED ISSUE(S) RECORDED`}
              </div>
            </div>
          </div>

          {/* Quantitative Summary Grid */}
          <div className="glass-subpanel grid grid-cols-2 sm:grid-cols-5 divide-y sm:divide-y-0 sm:divide-x divide-white/[0.08] rounded-xl font-mono tabular-nums">
            <div className="p-4">
              <div className="text-xs text-[#94A3B8]">Critical</div>
              <div className="text-xl font-semibold text-[#EF4444] mt-1">
                {criticalCount}
              </div>
            </div>
            <div className="p-4">
              <div className="text-xs text-[#94A3B8]">High</div>
              <div className="text-xl font-semibold text-[#F97316] mt-1">
                {highCount}
              </div>
            </div>
            <div className="p-4">
              <div className="text-xs text-[#94A3B8]">Medium</div>
              <div className="text-xl font-semibold text-[#F59E0B] mt-1">
                {mediumCount}
              </div>
            </div>
            <div className="p-4">
              <div className="text-xs text-[#94A3B8]">Low</div>
              <div className="text-xl font-semibold text-[#38BDF8] mt-1">
                {lowCount}
              </div>
            </div>
            <div className="col-span-2 sm:col-span-1 p-4">
              <div className="text-xs text-[#94A3B8]">Passed Controls</div>
              <div className="text-xl font-semibold text-[#10B981] mt-1">
                {report.passedChecks.length}
              </div>
            </div>
          </div>

          {/* Findings List */}
          <div className="space-y-3">
            <h3 className="font-display text-sm font-semibold text-white">
              Empirical Vulnerability Ledger ({report.findings.length})
            </h3>
            {report.findings.length === 0 ? (
              <div className="glass-subpanel rounded-xl p-5 text-sm text-[#10B981]">
                Zero exploitable vulnerabilities were detected across all active
                verification engines.
              </div>
            ) : (
              <div className="space-y-3">
                {report.findings.map((f, index) => (
                  <div
                    key={f.id}
                    className="glass-subpanel rounded-xl p-4 space-y-2"
                  >
                    <div className="flex flex-wrap items-center justify-between gap-2 text-xs font-mono">
                      <span className="font-semibold text-white">
                        {String(index + 1).padStart(2, '0')}. {f.title}
                      </span>
                      <span className="text-[#94A3B8]">
                        {f.severity.toUpperCase()} · {f.cwe} · {f.owasp}
                      </span>
                    </div>
                    <div className="text-xs font-mono text-[#38BDF8] break-all">
                      Target: {f.affectedTarget}
                    </div>
                    <p className="text-xs text-[#CBD5E1] leading-relaxed">
                      {f.summary}
                    </p>
                    <pre className="overflow-x-auto rounded-lg border border-white/[0.06] bg-black/40 p-3 font-mono text-[11px] text-[#CBD5E1]">
                      <code>{f.evidence.rawProof}</code>
                    </pre>
                  </div>
                ))}
              </div>
            )}
          </div>

          {/* Passed Security Controls */}
          <div className="space-y-3">
            <h3 className="font-display text-sm font-semibold text-white">
              Verified Passed Security Controls ({report.passedChecks.length})
            </h3>
            <div className="glass-subpanel divide-y divide-white/[0.06] rounded-xl">
              {report.passedChecks.map((pass) => (
                <div
                  key={pass.id}
                  className="flex flex-col sm:flex-row sm:items-center justify-between gap-2 px-4 py-2.5 text-xs"
                >
                  <div className="font-medium text-[#E2E8F0]">
                    <span className="font-mono text-[#10B981] mr-2">PASS</span>
                    {pass.title}
                  </div>
                  <div className="font-mono text-[#94A3B8] truncate max-w-md">
                    {pass.proofSummary}
                  </div>
                </div>
              ))}
            </div>
          </div>
        </div>
      </div>
    </div>
  );
};
